export const INITIAL_SCIENTIFIC_MUTUN: ScientificMatn[] = [
  TUHFAT_AL_ATFAL,
  AL_JAZARIYYAH
];

export function getDefaultScientificMutun(): ScientificMatn[] {
  return INITIAL_SCIENTIFIC_MUTUN;
}

export function getMatnById(id: string): ScientificMatn | undefined {
  return INITIAL_SCIENTIFIC_MUTUN.find(m => m.id === id);
}

export function createInitialStudentProgress(
  studentId: string,
  matn: ScientificMatn,
  studentName?: string,
  halqaId?: string,
  teacherId?: string
): MatnStudentProgress {
  const firstGroup = matn.groups[0];
  const firstGroupId = firstGroup ? firstGroup.id : "grp-01";

  const groupProgress: Record<string, any> = {};
  if (firstGroup) {
    groupProgress[firstGroupId] = {
      groupId: firstGroupId,
      groupNumber: 1,
      reviewCount: 0,
      selfQuizAttempts: 0,
      isTeacherApproved: false
    };
  }

  return {
    id: `${studentId}_${matn.id}`,
    studentId,
    studentName: studentName || "طالب المقرأة",
    halqaId,
    teacherId,
    matnId: matn.id,
    matnTitle: matn.title,
    currentGroupId: firstGroupId,
    currentGroupNumber: 1,
    completedGroupsCount: 0,
    totalGroupsCount: matn.groups.length,
    percentageCompleted: 0,
    lastStudiedAt: new Date().toISOString(),
    overallMasteryLevel: "good",
    groupProgress,
    nextGroupUnlocked: false, // مغلقة حتى اعتماد المعلم
    updatedAt: new Date().toISOString()
  };
}